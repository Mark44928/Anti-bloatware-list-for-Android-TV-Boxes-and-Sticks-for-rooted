#!/data/data/com.termux/files/usr/bin/env bash
# profile.sh — generate a device-specific tiered debloat/restore pair.
# Read-only on the device; it never removes packages or calls install-existing.
set -euo pipefail

usage() {
  echo "usage: profile.sh [--tier safe|full] [--output DIR] [--dry-run]"
  echo "  safe   universal-safe packages only (default)"
  echo "  full   every target in debloat.sh"
  echo "  output where to write profile.sh scripts (default: current directory)"
  echo "  dry-run print the selected packages without writing files"
}

TIER=safe
OUTPUT=.
DRY_RUN=0
case "${1:-}" in
  --help|-h) usage; exit 0 ;;
esac
while [ "$#" -gt 0 ]; do
  case "$1" in
    --tier) [ $# -ge 2 ] || { echo "profile.sh: --tier needs safe or full" >&2; exit 2; }; TIER="$2"; shift ;;
    --tier=*) TIER="${1#--tier=}" ;;
    --output) [ $# -ge 2 ] || { echo "profile.sh: --output needs a directory" >&2; exit 2; }; OUTPUT="$2"; shift ;;
    --output=*) OUTPUT="${1#--output=}" ;;
    --dry-run|-n) DRY_RUN=1 ;;
    *) echo "profile.sh: unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

case "$TIER" in safe|full) ;; *) echo "profile.sh: --tier must be safe or full" >&2; exit 2 ;; esac

HERE="$(cd "$(dirname "$0")" && pwd)"
cd "$HERE"
command -v pm >/dev/null 2>&1 || { echo "pm is required (run on an Android device)" >&2; exit 1; }

mapfile -t SAFE < <(awk '/^PKGS=\(/,/^\)/ { if ($1 ~ /^com\./) print $1 }' debloat-safe.sh)
mapfile -t FULL < <(awk '/^PKGS=\(/,/^\)/ { if ($1 ~ /^com\./) print $1 }' debloat.sh)
if [ "$TIER" = "safe" ]; then
  mapfile -t TARGETS < <(printf '%s\n' "${SAFE[@]}")
else
  mapfile -t TARGETS < <(printf '%s\n' "${FULL[@]}")
fi

audit_json=$(bash audit.sh --json)

# Parse the compact audit JSON without a dependency on a JSON parser.
declare -A STATE=()
while IFS= read -r record; do
  pkg=$(printf '%s' "$record" | sed -E 's/.*"package":"([^"]*)".*/\1/')
  state=$(printf '%s' "$record" | sed -E 's/.*"state":"([^"]*)".*/\1/')
  STATE["$pkg"]="$state"
done < <(printf '%s\n' "$audit_json" | grep -oE '\{"package":"[^"]*","state":"[^"]*"\}')

declare -A SELECTED=()
for pkg in "${TARGETS[@]}"; do
  state="${STATE[$pkg]:-absent}"
  case "$state" in
    enabled|installed) SELECTED["$pkg"]=1 ;;
  esac
done

count=${#SELECTED[@]}
echo "Profile tier: $TIER"
echo "Enabled or partially enabled targets: $count"
if [ "$count" -eq 0 ]; then
  echo "Nothing to generate; every target is absent or already disabled."
  exit 0
fi
printf '  %s\n' "${!SELECTED[@]}" | sort

if [ "$DRY_RUN" = "1" ]; then
  echo "dry run: no scripts written"
  exit 0
fi

mkdir -p "$OUTPUT"
DEST_DEBLOAT="$OUTPUT/script-debloat-$TIER.sh"
DEST_RESTORE="$OUTPUT/script-restore-$TIER.sh"

{
  echo '#!/data/data/com.termux/files/usr/bin/env bash'
  echo 'set -u'
  echo "# Generated by profile.sh for this device. Review before running."
  echo "# Tier: $TIER · packages selected from live pm state."
  echo 'case "${1:-}" in'
  echo '  "") ;;'
  echo '  --dry-run|-n) DRY=1 ;;'
  echo '  --help|-h) echo "usage: $0 [--dry-run]"; exit 0 ;;'
  echo '  *) echo "unknown option: $1" >&2; exit 2 ;;'
  echo 'esac'
  echo 'DRY=${DRY:-0}'
  echo 'PKGS=('
  for pkg in "${!SELECTED[@]}"; do printf '  "%s"\n' "$pkg"; done | sort
  echo ')'
  echo 'removed=0; planned=0; skipped=0'
  echo 'for p in "${PKGS[@]}"; do'
  echo '  if pm list packages | grep -Fqx "package:$p"; then'
  echo '    if [ "$DRY" = "1" ]; then echo "would remove $p"; planned=$((planned + 1));'
  echo '    elif pm uninstall --user 0 "$p" >/dev/null 2>&1; then echo "removed  $p"; removed=$((removed + 1));'
  echo '    else echo "FAILED   $p"; fi'
  echo '  else echo "skip     $p (not installed)"; skipped=$((skipped + 1)); fi'
  echo 'done'
  echo 'echo'
  echo 'if [ "$DRY" = "1" ]; then echo "dry run: $planned would be removed, $skipped absent/skipped."; else echo "done: $removed removed, $skipped not present/skipped. Reboot to settle."; fi'
} > "$DEST_DEBLOAT"

{
  echo '#!/data/data/com.termux/files/usr/bin/env bash'
  echo 'set -u'
  echo "# Restore helper for script-debloat-$TIER.sh. Generated by profile.sh."
  echo "# Tier: $TIER · only the packages removed by the generated debloat script."
  echo 'case "${1:-}" in'
  echo '  "") ;;'
  echo '  --dry-run|-n) DRY=1 ;;'
  echo '  --help|-h) echo "usage: $0 [--dry-run]"; exit 0 ;;'
  echo '  *) echo "unknown option: $1" >&2; exit 2 ;;'
  echo 'esac'
  echo 'DRY=${DRY:-0}'
  echo 'PKGS=('
  for pkg in "${!SELECTED[@]}"; do printf '  "%s"\n' "$pkg"; done | sort
  echo ')'
  echo 'restored=0; planned=0; missing=0'
  echo 'for p in "${PKGS[@]}"; do'
  echo '  if pm list packages -u | grep -Fqx "package:$p"; then'
  echo '    if [ "$DRY" = "1" ]; then echo "would restore $p"; planned=$((planned + 1));'
  echo '    elif cmd package install-existing "$p" >/dev/null 2>&1; then echo "restored $p"; restored=$((restored + 1));'
  echo '    else echo "FAILED   $p"; fi'
  echo '  else echo "absent   $p (fully uninstalled — sideload the APK)"; missing=$((missing + 1)); fi'
  echo 'done'
  echo 'echo'
  echo 'if [ "$DRY" = "1" ]; then echo "dry run: $planned would be restored, $missing absent. Nothing changed."; else echo "done: $restored restored, $missing absent. Reboot to settle."; fi'
} > "$DEST_RESTORE"
chmod +x "$DEST_DEBLOAT" "$DEST_RESTORE"
echo "wrote $DEST_DEBLOAT"
echo "wrote $DEST_RESTORE"
